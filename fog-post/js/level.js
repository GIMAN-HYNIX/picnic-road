/* 지형 높이 */
function groundAt(x) {
  for (const s of LV.segs) {
    if (x < s[0][0] || x > s[s.length - 1][0]) continue;
    for (let i = 0; i < s.length - 1; i++) {
      const p = s[i], q = s[i + 1];
      if (x >= p[0] && x <= q[0]) { const t = (x - p[0]) / ((q[0] - p[0]) || 1); return { y: p[1] + (q[1] - p[1]) * t, slope: (q[1] - p[1]) / ((q[0] - p[0]) || 1) }; }
    }
  }
  return null;
}
function inWaterX(x) { return x > LV.water.x0 && x < LV.water.x1; }
const VCYCLE = 3.4;
function ventState(v, t) {
  const c = ((t + v.off) % VCYCLE + VCYCLE) % VCYCLE;
  if (c < 1.0) return { k: 'safe', a: .12 };
  if (c < 1.8) return { k: 'warn', a: .12 + .5 * ((c - 1.0) / .8) };
  if (c < 3.0) return { k: 'active', a: 1 };
  return { k: 'fade', a: 1 - .85 * ((c - 3.0) / .4) };
}
