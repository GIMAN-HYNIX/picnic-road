/* =========================================================
   칼질 실험실 · B(손그림식) 기반 새 시안 다섯 가지
   장면을 하나씩 손으로 잡는 방식: [머무는 프레임 수, 바뀌는 자세 값, { s: 칼 잔상, h: 몇 타, c: 컷 이름 }]
   적지 않은 값은 앞 장면 그대로 이어짐 (눌림 sq만 장면마다 0으로 돌아감)
   ========================================================= */
function mkPoses(id, poses, names) {
  let cur = Object.assign({}, G0), t = 0, prevT = 0;
  const keys = [], list = [], hits = names.map(name => ({ name, cuts: [], caps: [] }));
  for (const [hold, ch, o = {}] of poses) {
    cur = Object.assign({}, cur, { sq: 0 }, ch); keys.push([t, cur]);
    if (hold > 0) {
      list.push([t, hold, null, o.s ? t - prevT : 0]);
      if (o.h) { hits[o.h - 1].cuts.push(t); hits[o.h - 1].caps.push(o.c || ''); }
      prevT = t;
    }
    t += Math.max(hold, 1);
  }
  return mkStepped(id, wTrack(keys), list, hits);
}
